"""Review recorded evidence using explicit, documented attack success rules."""
import argparse
from collections import Counter
import json
from pathlib import Path

import config

EVASION_DIAGNOSES = {
    'EV01': ('signal one / combining rule', 'Typos lower model score to 0.1635 while style stays at 0.6226; the 0.8 model weight pulls the result to 0.2553.'),
    'EV02': ('signal two / combining rule', 'Broken-up sentences lower the style score to 0.2927; the weighted score stays inside the unsure band.'),
    'EV03': ('signal two / combining rule', 'The pasted quotation changes surface counts; both reported signals remain below the AI-label cutoff.'),
    'EV04': ('signal one', 'Unusual words increase perplexity; predictability is not a reliable authorship test, so the score stays below the AI cutoff.'),
    'EV05': ('both signals', 'Heavy editing lowers both signals, and their weighted mean remains unsure.'),
    'EV06': ('signal two', 'Unequal sentence lengths lower the variation component; the result does not cross the AI-label threshold.'),
    'EV07': ('signal two', 'Added punctuation lowers the punctuation component without establishing a different author; the combined result is unsure.'),
    'EV08': ('signal one / route', 'The short input still contains enough tokens to pass validation; its score of 0.3008 is unsure, not an AI flag.'),
    'EV09': ('both signals / combining rule', 'The added opening alters both predictability and surface statistics; the combined result is below the AI cutoff.'),
}


def assess_attack(row, decision_entries):
    status, guess, attack_id = row['status'], row['guess'], row['id']
    if row.get('error') or status is None or status >= 500:
        return 'BROKE', 'route', 'The request failed or returned an unusable response.'
    family = row['family']
    if family == 'flood_same_creator':
        index = int(attack_id.rsplit('_', 1)[1])
        expected = 200 if index <= config.RATE_LIMIT_PER_MINUTE else 429
        ok = status == expected
        return ('HELD' if ok else 'BROKE'), 'route', f'Request {index}: expected HTTP {expected} within this fresh-process minute budget.'
    if status == 429:
        return 'HELD', 'route', 'Limiter blocked the request; its handler behavior was not exercised.'
    if family == 'evasion':
        if status == 200 and guess != 'ai':
            stage, note = EVASION_DIAGNOSES.get(attack_id, ('label mapping', 'AI-like input did not receive an AI label.'))
            return 'BROKE', stage, note
        return 'HELD', 'label mapping', 'The attempted evasion still received the AI label or was rejected.'
    if family == 'false_positive':
        return ('BROKE' if guess == 'ai' else 'HELD'), 'label mapping', 'A human-writing attack breaks the check only if it receives the AI label.'
    if family == 'prompt_injection':
        matches = [e for e in decision_entries if e.get('content_id') == row['content_id']]
        expected_keys = {'timestamp', 'content_id', 'creator_id', 'guess', 'model_score', 'style_score', 'combined_score', 'label', 'status'}
        ok = (status == 200 and len(matches) == 1 and set(matches[0]) == expected_keys
              and matches[0]['guess'] == guess and matches[0]['label'] == row['label']
              and row['label'] in {
                  'This writing appears more likely to have been written by a person, but the estimate may be wrong.',
                  "We can't tell reliably how this writing was created. You can appeal this assessment.",
                  'This writing may have been generated by AI. This is an estimate and can be appealed.'})
        return ('HELD' if ok else 'BROKE'), 'route / label mapping', 'The input remained data: a normal score, a fixed label, and one unmodified-schema decision entry were recorded.'
    if attack_id == 'MF07':
        if guess == 'ai':
            return 'BROKE', 'signal two / signal one', 'Arabic text has no words under the ASCII-only tokenizer; style rises to 0.7762, and GPT-2 gives 0.9064. Their mean becomes a confident AI accusation without validated language support.'
        return 'HELD', 'label mapping', 'Valid Arabic text is accepted without a confident AI accusation; language support is still unvalidated.'
    if attack_id in {'MF03', 'MF04', 'MF05', 'MF06'}:
        if status == 200:
            return 'BROKE', 'route', 'The string passes the length/token checks despite controls or non-prose content; a provenance decision is made without a suitable writing sample.'
    ok = status == 400
    return ('HELD' if ok else 'BROKE'), 'route', 'The malformed input should be rejected with HTTP 400.'


def review(label):
    raw_path = max(Path('results').glob(f'attack_run_*_{label}.json'))
    raw = json.loads(raw_path.read_text(encoding='utf-8'))
    audit_path = max(Path('results').glob(f'attacks_{label}_*.audit.jsonl'))
    entries = [json.loads(line) for line in audit_path.read_text(encoding='utf-8').splitlines() if line]
    rows = []
    for source in raw['rows']:
        verdict, stage, mechanism = assess_attack(source, entries)
        rows.append({**source, 'verdict': verdict, 'stage': stage, 'mechanism': mechanism})
    data = {'source': str(raw_path), 'audit_source': str(audit_path), 'rows': rows,
            'totals': dict(Counter(r['verdict'] for r in rows))}
    prefix = Path('results') / f'reviewed_attacks_{label}'
    prefix.with_suffix('.json').write_text(json.dumps(data, indent=2), encoding='utf-8')
    lines = [f'# Reviewed attacks: {label}', '',
             'Evasion: BROKE means a successful response without an AI flag (including unsure). False positive: BROKE means an AI accusation. Junk strings: BROKE means a decision was made instead of refusal. Arabic is legitimate writing; a confident AI accusation is treated as the failure, not acceptance of its script. Prompt injection: check fixed response labels and audit integrity. Flood: accept within budget and reject above it.', '',
             f'Totals: {data["totals"]}', '',
             '| ID | Status | Guess | Combined | Verdict | Stage and mechanism |', '|---|---|---|---|---|---|']
    for r in rows:
        lines.append(f'| {r["id"]} | {r["status"]} | {r["guess"] or "-"} | {r["confidence"]} | {r["verdict"]} | {r["stage"]}: {r["mechanism"]} |')
    prefix.with_suffix('.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(json.dumps(data['totals']))
    return data


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--label', choices=['before', 'after'], required=True)
    review(parser.parse_args().label)
