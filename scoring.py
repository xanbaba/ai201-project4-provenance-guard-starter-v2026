"""Combine AI-likelihood signals and map the result to a reader-facing label."""
import config


def combine_signals(model_score: float, style_score: float) -> float:
    """Weighted average; higher scores indicate more AI-like writing."""
    return round(config.WEIGHT_MODEL_SIGNAL * model_score + config.WEIGHT_STYLE_SIGNAL * style_score, 4)


def score_to_label(score: float) -> tuple[str, str]:
    """Return the guess and label; thresholds include their boundary values."""
    if score >= config.AI_THRESHOLD:
        return "ai", "This writing may have been generated by AI. This is an estimate and can be appealed."
    if score <= config.HUMAN_THRESHOLD:
        return "human", "This writing appears more likely to have been written by a person, but the estimate may be wrong."
    return "unsure", "We can't tell reliably how this writing was created. You can appeal this assessment."


def label_ranges() -> list[tuple[str, str]]:
    return [("high-confidence human", f"0.00 to {config.HUMAN_THRESHOLD:.2f} inclusive"),
            ("unsure", f"above {config.HUMAN_THRESHOLD:.2f} and below {config.AI_THRESHOLD:.2f}"),
            ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} to 1.00 inclusive")]
